/**
 * মোবাইলের সাইজ ইউনিট।
 *
 * মূল সাইটের মোবাইল বিল্ড ৭৫০px ডিজাইনে আঁকা, আর `html` এর font-size
 * `100vw / 7.5` — অর্থাৎ **1rem = ডিজাইনের ১০০px**। তাই ডিজাইনে মাপা
 * যেকোনো সংখ্যা সরাসরি `m(n)` দিয়ে লেখা যায়:
 *
 *   m(110) → "1.1rem"   (ডিজাইনের ১১০px, ৩৯০px ফোনে ৫৭.২px)
 *
 * সব মাপ power7.live এর মোবাইল বিল্ড থেকে getBoundingClientRect দিয়ে
 * নেওয়া, তারপর rem বেস (৫২px @390) দিয়ে ভাগ করে ৭৫০-ডিজাইনে ফেরানো।
 */
export const m = (n) => `${n / 100}rem`;

export default m;
